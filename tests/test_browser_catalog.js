const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const crypto = require('node:crypto');
const {TextEncoder, TextDecoder} = require('node:util');
const local = new Map();
const raw = JSON.stringify({id:'shared.1', label:'Shared', status:'running', results:[]});
const digest = crypto.createHash('sha256').update(raw).digest('hex');
let broken = false, requests = [];
const storage = {getItem:k=>local.get(k) || null, setItem:(k,v)=>local.set(k,v)};
const window = {WATTEVER_STATIC:true, localStorage:storage, crypto:crypto.webcrypto};
const fetch = async url => {
  const u = String(url); requests.push(u);
  if (u.endsWith('/index.json')) return {ok:true,json:async()=>({version:1,benchmarks:[{id:'shared.1',file:'shared.1.json',sha256:broken?'0'.repeat(64):digest}]})};
  if (u.endsWith('/shared.1.json')) return {ok:true,arrayBuffer:async()=>new TextEncoder().encode(raw).buffer};
  throw Error('unexpected fetch '+u);
};
const ctx = {window, fetch, URL, document:{baseURI:'https://example.test/site/'}, TextEncoder, TextDecoder, Uint8Array, AbortController, setTimeout, clearTimeout, performance};
vm.runInNewContext(fs.readFileSync('web/browser.js','utf8'),ctx);
(async()=>{
  const api = window.WatteverBrowser;
  assert.equal(requests.length,0);
  let listing = await api.request('/api/runs');
  assert.equal(listing.runs.length,1); assert.equal(listing.runs[0].community,true); assert.equal(listing.runs[0].status,'interrupted');
  assert(requests.every(url=>url.startsWith('https://example.test/site/benchmarks/')));
  assert.equal(local.has('wattever.browser.runs.v1'),false);
  const shared = await api.request('/api/runs/shared.1'); assert.equal(shared.label,'Shared'); assert.equal(shared.status,'interrupted'); assert.equal(shared.source_status,'running'); assert.equal(JSON.parse(raw).status,'running');
  const downloaded = await api.request('/api/runs/shared.1/download'); assert.equal(downloaded.community, undefined);
  assert.equal((await api.request('/api/export.json')).runs[0].community, undefined);
  await assert.rejects(api.request('/api/runs/shared.1/meta',{method:'POST',body:'{}'}),/read-only/);
  const imported = api.importRun({id:'shared.1',label:'Local',results:[]});
  assert.notEqual(imported.id,'shared.1'); assert.equal(imported.source_run_id,'shared.1');
  assert.equal((await api.request('/api/runs')).runs.length,2);
  await api.request('/api/runs/'+imported.id,{method:'DELETE'});
  assert.equal((await api.request('/api/runs')).runs[0].community,true);
  await api.request('/api/runs/shared.1',{method:'DELETE'});
  assert.equal((await api.request('/api/runs')).runs.length,0);
  assert(local.get('wattever.browser.hidden-community.v1').includes('shared.1'));
  api.importRun({id:'local-only',label:'Local',results:[]});
  listing = await api.request('/api/runs'); assert.equal(listing.runs[0].label,'Local'); assert.equal(listing.runs[0].community,false);
  broken = true; await api.loadCommunity(true);
  listing = await api.request('/api/runs'); assert(listing.community_error); assert.equal(listing.runs[0].label,'Local');
  const timeoutWindow = {WATTEVER_STATIC:true, crypto:crypto.webcrypto, localStorage:{getItem:k=>k==='wattever.browser.runs.v1' ? JSON.stringify([{id:'saved',results:[]}]) : null, setItem:()=>{}}};
  let abortSignal;
  const timeoutCtx = {...ctx, window:timeoutWindow, fetch:(_url, opts)=>{abortSignal=opts.signal; return new Promise(()=>{});}, setTimeout:(fn,ms)=>setTimeout(fn,ms===10000?1:ms)};
  vm.runInNewContext(fs.readFileSync('web/browser.js','utf8'),timeoutCtx);
  const stalled = timeoutWindow.WatteverBrowser;
  assert.equal((await stalled.request('/api/runs/saved')).id,'saved');
  const stalledList = await stalled.request('/api/runs');
  assert.equal(stalledList.runs[0].id,'saved'); assert(stalledList.community_error); assert(abortSignal.aborted);
  console.log('community catalog tests passed');
})().catch(error=>{console.error(error);process.exitCode=1});
