const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),crypto=require('node:crypto');
const {TextEncoder,TextDecoder}=require('node:util');
const storage=new Map(),calls=[];
let advertisedService=null;
const window={WATTEVER_STATIC:true,crypto:crypto.webcrypto,localStorage:{getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,value)}};
const context={window,URL,document:{baseURI:'https://example.test/'},TextEncoder,TextDecoder,Uint8Array,AbortController,setTimeout,clearTimeout,performance,
  fetch:async(url)=>{
    calls.push(String(url));
    const path=new URL(url).pathname;
    if(path.endsWith('/models'))return{ok:true,headers:{get:()=>null},json:async()=>({data:[{id:'strata-looking-model-name'}]})};
    return{ok:true,headers:{get:()=>null},json:async()=>advertisedService?{service:advertisedService,version:'0.2.6'}:{status:'ok'}};
  }};
vm.runInNewContext(fs.readFileSync('web/browser.js','utf8'),context);
const adapter=window.WatteverBrowser;
(async()=>{
  assert.throws(()=>adapter.configure({endpoint:''}),/API base URL/);
  adapter.configure({endpoint:'http://localhost:8086/v1'});
  const generic=(await adapter.connect()).endpoint_identity;
  assert.equal(generic.label,'Local endpoint');
  assert.equal(generic.source,'unknown');
  assert(!generic.label.toLowerCase().includes('strata'));
  advertisedService='strata';
  adapter.configure({endpoint:'http://localhost:8086/v1'});
  const identified=(await adapter.connect()).endpoint_identity;
  assert.equal(identified.source,'detected');
  assert.equal(identified.service,'Strata');
  assert.equal(identified.version,'0.2.6');
  assert.equal(identified.id,generic.id,'A route keeps its random ID as better metadata becomes available');
  adapter.configure({endpoint:'http://localhost:8181/v1',endpoint_name_override:'My comparison'});
  const overridden=(await adapter.connect()).endpoint_identity;
  assert.equal(overridden.label,'My comparison');assert.equal(overridden.source,'operator_override');
  assert.notEqual(overridden.id,identified.id);
  const publicId=overridden.id;
  adapter.configure({endpoint:'http://localhost:8181/v1'});
  assert.equal((await adapter.connect()).endpoint_identity.id,publicId);
  adapter.configure({endpoint:'https://api.openai.com/v1'});
  calls.length=0;
  const official=(await adapter.connect()).endpoint_identity;
  assert.equal(official.id,'openai-api');assert.equal(official.label,'OpenAI API');
  assert.equal(calls.length,1,'Known public providers need no speculative metadata requests');
  adapter.configure({endpoint:'https://api.openai.com/custom-private-route/v1'});
  const custom=(await adapter.connect()).endpoint_identity;
  assert.notEqual(custom.id,official.id);assert(!JSON.stringify(custom).includes('custom-private-route'));
  advertisedService=null;
  adapter.configure({endpoint:'https://api.openai.com.attacker.invalid/v1'});
  const unrelated=(await adapter.connect()).endpoint_identity;
  assert.equal(unrelated.label,'Remote endpoint');assert.equal(unrelated.service,'unknown');
  assert(!JSON.stringify(unrelated).includes('attacker.invalid'));
  console.log('Browser automatic endpoint identity tests passed');
})().catch(error=>{console.error(error);process.exitCode=1});
